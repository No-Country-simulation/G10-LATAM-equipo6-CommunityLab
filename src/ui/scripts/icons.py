def icon_svg(
    name: str,
    size: int = 16,
    color: str = "currentColor",
    stroke_width: float = 2.0,
    extra_style: str = "",
    extra_class: str = "",
) -> str:
    """Genera un fragmento SVG inline de Lucide listo para insertar en HTML."""
    path = LUCIDE_PATHS.get(name, LUCIDE_PATHS.get("sparkles", ""))
    style = f"vertical-align: middle; display: inline-block; {extra_style}".strip()
    return (
        f'<svg xmlns="http://www.w3.org/2000/svg" width="{size}" height="{size}" '
        f'viewBox="0 0 24 24" fill="none" stroke="{color}" stroke-width="{stroke_width}" '
        f'stroke-linecap="round" stroke-linejoin="round" class="lucide-icon {extra_class}" '
        f'style="{style}">{path}</svg>'
    )


def icon_badge(
    name: str,
    text: str,
    bg_color: str = "rgba(99, 91, 255, 0.12)",
    text_color: str = "#635BFF",
    size: int = 14,
) -> str:
    """Genera una píldora visual estilizada con icono SVG."""
    svg = icon_svg(name, size=size, color=text_color)
    return (
        f'<span style="display:inline-flex; align-items:center; gap:5px; '
        f'background:{bg_color}; color:{text_color}; padding:3px 9px; '
        f'border-radius:12px; font-size:0.75rem; font-weight:600; line-height:1;">'
        f'{svg} <span>{text}</span></span>'
    )


def get_material_icon(key: str) -> Optional[str]:
    """Retorna el símbolo Material nativo de Streamlit para widgets interactivos."""
    return MATERIAL_ICONS.get(key)
